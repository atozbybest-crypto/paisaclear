SSY_VS_PPF = """
    <h2 class="guide-h2">What the table does not show</h2>
    <p class="guide-p">
      The two schemes look similar because both are government-backed and both are tax-free. The difference is in
      who may hold one and what the money is for. PPF is open to any resident individual; SSY requires a girl
      child under ten, and the account is operated by a guardian until she turns eighteen.
    </p>
    <p class="guide-p">
      That single eligibility rule decides most cases. If there is no daughter under ten in the household, the
      comparison is academic.
    </p>

    <h2 class="guide-h2">The rate gap, over a full term</h2>
    <p class="guide-p">
      SSY pays 1.10 percentage points more than PPF at the current notification. On ₹1.5 lakh a year for fifteen
      years, that gap is worth several lakh at maturity — not because of a clever strategy, but because a
      percentage point, compounded for two decades, is a large amount of money.
    </p>
    <p class="guide-p">
      Neither rate is fixed for the life of the account. Both are notified quarterly, and both apply the new rate
      to the whole balance. A saver who opens an SSY account today is not locking 8.20% for twenty-one years.
    </p>

    <h2 class="guide-h2">The access rules are not the same</h2>
    <ul class="check-list">
      <li><span><strong>PPF:</strong> loan from year three, partial withdrawal from year six, closes at fifteen with the option to extend.</span></li>
      <li><span><strong>SSY:</strong> partial withdrawal of up to 50% for education once she turns eighteen or passes Class 10; closure for marriage after eighteen; matures at twenty-one.</span></li>
      <li><span><strong>PPF is more flexible</strong> for the first fifteen years. SSY is more generous at the end, because the money compounds for six years after deposits stop.</span></li>
    </ul>

    <h2 class="guide-h2">A practical way to hold both</h2>
    <p class="guide-p">
      They are not competing for the same rupee. A household with a daughter can use SSY for her education and
      PPF for everything else — retirement, a house deposit, a general reserve. The ₹1.5 lakh 80C limit is shared,
      so the split matters for tax, but the two accounts do different jobs.
    </p>
    <p class="guide-p">
      What you should not do is fund SSY by withdrawing from PPF, or treat either as an emergency fund. Both take
      days to close and both penalise early exits in ways that surprise people.
    </p>
"""

NPS_VS_PPF = """
    <h2 class="guide-h2">These are not substitutes</h2>
    <p class="guide-p">
      PPF is a savings account with a guaranteed rate and no market risk. NPS is a pension product that invests
      in equity and debt, charges a fund management fee, and locks the corpus until sixty. Comparing their
      "returns" is comparing a certainty with a distribution of outcomes.
    </p>
    <p class="guide-p">
      The useful question is not which earns more. It is which job each does. PPF builds a tax-free reserve you
      can reach in a crisis after six years. NPS builds retirement income you cannot touch, with part of the
      corpus compulsorily annuitised at the end.
    </p>

    <h2 class="guide-h2">The lock-in is the point, and the problem</h2>
    <p class="guide-p">
      NPS money cannot be withdrawn before sixty except in narrow circumstances — buying a first home, medical
      treatment, education — and each has conditions. That is deliberate: a pension that can be raided is not a
      pension. It is also why NPS should never hold money you might need.
    </p>

    <h2 class="guide-h2">The tax treatment differs in one important way</h2>
    <p class="guide-p">
      PPF is exempt at all three stages: the deposit, the interest and the maturity. NPS is exempt on the way in
      within limits, exempt on the corpus at sixty for the invested portion, but the annuity income you buy with
      the mandatory slice is taxed as ordinary income.
    </p>
    <p class="guide-p">
      That difference matters more the higher your slab. A 30% taxpayer exchanging a fully exempt product for a
      partially taxable one needs a materially higher return to break even — and NPS returns are not guaranteed.
    </p>

    <h2 class="guide-h2">Who should hold which</h2>
    <ul class="check-list">
      <li><span><strong>PPF first</strong> for anyone without a guaranteed, liquid, tax-free reserve.</span></li>
      <li><span><strong>NPS</strong> for someone with a long horizon, a high slab, and a retirement plan that needs a market-linked sleeve.</span></li>
      <li><span><strong>Both</strong> is common and reasonable: PPF for the accessible tax-free layer, NPS for the locked retirement layer.</span></li>
    </ul>
"""

SCSS_VS_FD = """
    <h2 class="guide-h2">The rate is only half the comparison</h2>
    <p class="guide-p">
      SCSS currently pays more than most senior-citizen fixed deposits. But a deposit and a government scheme
      differ on three things that the rate does not capture: who guarantees the money, how easily it can be
      broken, and how often the interest is paid.
    </p>

    <h2 class="guide-h2">Safety above five lakh</h2>
    <p class="guide-p">
      Bank deposits are insured up to ₹5 lakh per depositor per bank. Above that, you are a creditor of the bank.
      For a retiree parking ₹25 lakh, that is the decisive fact: SCSS is a sovereign obligation, and no part of it
      depends on a bank's balance sheet.
    </p>
    <p class="guide-p">
      The practical answer for most people is both — SCSS up to the ₹30 lakh cap, and deposits spread across
      banks within the insured limit — rather than arguing about 40 basis points.
    </p>

    <h2 class="guide-h2">Flexibility is what you give up</h2>
    <p class="guide-p">
      A fixed deposit can be broken in an afternoon with a small penalty. SCSS allows premature closure only
      after a year, with a penalty on the rate already paid, and it is designed for people who do not intend to
      touch the capital.
    </p>
    <p class="guide-p">
      That makes SCSS a poor home for the money you might need for a medical bill — and a good home for the money
      that must produce income for five years without drama.
    </p>

    <h2 class="guide-h2">Quarterly income, not compounding</h2>
    <p class="guide-p">
      SCSS pays interest out every quarter. An FD can compound or pay out, depending on the option you choose.
      If you do not need the income, the compounding option inside a deposit will compound; SCSS will not, unless
      you reinvest each payout yourself.
    </p>
    <p class="guide-p">
      Retirees often spend the quarterly interest without noticing. That is fine if the budget needs it, and a
      quiet erosion of the corpus if it does not.
    </p>

    <h2 class="guide-h2">One more difference: age</h2>
    <p class="guide-p">
      SCSS requires you to be sixty, or fifty-five to sixty and retired on superannuation or under a VRS. An FD
      has no age condition beyond the bank's senior-citizen rate threshold. If you are under sixty, this
      comparison does not apply to you at all.
    </p>
"""

SIP_VS_FD = """
    <h2 class="guide-h2">The question underneath the question</h2>
    <p class="guide-p">
      A fixed deposit answers "what will I have?" A SIP answers "what might I have?" Choosing between them is
      not a judgement about which product is better — it is a judgement about whether you can afford the answer
      to be wrong.
    </p>
    <p class="guide-p">
      That is why the horizon decides almost everything. Money needed in two years cannot be in equity, because a
      20% fall in year one leaves no time to recover. Money needed in fifteen years should not be entirely in a
      deposit, because a taxable 7% return barely beats inflation.
    </p>

    <h2 class="guide-h2">What the SIP illustration leaves out</h2>
    <ul class="check-list">
      <li><span><strong>Sequence.</strong> The order of returns matters as much as the average. A bad first three years on a fifteen-year SIP is recoverable; a bad final three years is not.</span></li>
      <li><span><strong>Tax.</strong> Equity gains above the exemption are taxed on redemption. The FD's interest is taxed every year, which is worse for compounding but easier to plan.</span></li>
      <li><span><strong>Discipline.</strong> A SIP only works if the instalment is paid in the months when the market is falling and it feels pointless. That is the entire mechanism.</span></li>
    </ul>

    <h2 class="guide-h2">Why the FD still earns a place</h2>
    <p class="guide-p">
      An FD is a promise with a date on it. That is valuable for money that must arrive on a date — a school fee,
      a tax payment, a deposit on a house. No market-linked product can promise that, and pretending otherwise is
      how people end up selling equity at the bottom to meet a bill.
    </p>

    <h2 class="guide-h2">A structure that uses both</h2>
    <ol class="guide-list">
      <li>Three to six months of expenses in a savings account or liquid fund.</li>
      <li>Money needed within three years in deposits — the date matters more than the return.</li>
      <li>Money needed after seven years in a SIP, with the instalment sized so a 30% fall does not force a sale.</li>
    </ol>
    <p class="guide-p">
      The point of the split is that no single event forces you to break the wrong product at the wrong time.
    </p>
"""

TAX_REGIME = """
    <h2 class="guide-h2">Why the lower-rate regime often loses</h2>
    <p class="guide-p">
      The new regime advertises wider slabs and a higher rebate. The old regime keeps deductions the new one
      gives up: 80C, 80D, HRA, home-loan interest, and the standard deduction for salaried taxpayers in both.
      At low to middle incomes with substantial deductions, the old regime can still win despite higher rates.
    </p>
    <p class="guide-p">
      The break-even is not a fixed income level — it depends on how much you actually claim. An employee with
      ₹2 lakh of 80C and 80D claims is in a different position from one with none, at the same salary.
    </p>

    <h2 class="guide-h2">What counts as a real deduction</h2>
    <ul class="check-list">
      <li><span><strong>80C:</strong> PPF, ELSS, life insurance premium, principal on a home loan, tuition fees, EPF — capped at ₹1.5 lakh in total.</span></li>
      <li><span><strong>80D:</strong> health insurance premiums, plus a separate allowance for parents.</span></li>
      <li><span><strong>HRA:</strong> the smallest of three calculations — actual HRA, rent minus 10% of basic, or 50%/40% of basic by city.</span></li>
      <li><span><strong>Home-loan interest:</strong> up to ₹2 lakh on a self-occupied property.</span></li>
    </ul>

    <h2 class="guide-h2">The trap in switching</h2>
    <p class="guide-p">
      Salaried taxpayers can switch regime every year, and the employer applies whichever you declare. Business
      income has stricter rules, with a limited number of switches. If you switch to the new regime and later
      want the old one, the deductions you did not claim are gone — you cannot claim them retrospectively.
    </p>

    <h2 class="guide-h2">How to decide in ten minutes</h2>
    <p class="guide-p">
      Add up the deductions you can genuinely claim this year. Subtract them from your gross income. Run both
      regimes on that number. Choose the lower tax — not the lower slab rate. Then check the same arithmetic for
      next year, because a home loan ending or a child starting school changes it.
    </p>
    <p class="guide-p">
      The comparison is annual, not permanent. People who choose once and never revisit it usually overpay in the
      years their circumstances change.
    </p>
"""

