DIVIDEND = _shell(
    "What a 25-year dividend streak actually predicts",
    "A long record is evidence of a habit. It is not a forecast — and the difference costs people money.",
    "Reviewed 15 November 2026",
    """
    <p class="guide-p">
      A company that has paid a dividend every year for twenty-five years is making a statement about how it
      runs itself. It is not making a promise about next year. Investors routinely confuse the two, and the
      confusion is expensive because the shares that carry the longest records are usually the ones trading at
      a premium for exactly that reason.
    </p>

    <h2 class="guide-h2">What the streak actually tells you</h2>
    <p class="guide-p">
      Three things, and all three are useful.
    </p>
    <ul class="check-list">
      <li><span><strong>The board treats the dividend as a commitment.</strong> Companies cut dividends reluctantly, because the market punishes the cut harder than it rewards the increase. A twenty-five-year record means several boards, across several downturns, chose to protect the payout.</span></li>
      <li><span><strong>Cash has been real, not accounting.</strong> A dividend is paid in rupees. A company cannot pay one for twenty-five years out of paper profits alone.</span></li>
      <li><span><strong>Capital allocation has been disciplined.</strong> Paying out cash means not spending it on everything else — a signal about management's restraint.</span></li>
    </ul>

    <h2 class="guide-h2">What it does not tell you</h2>
    <p class="guide-p">
      It does not tell you the dividend will be maintained. It does not tell you the payout is affordable
      today. And it does not tell you the share price is a good price.
    </p>
    <p class="guide-p">
      Two numbers matter more than the length of the record: the <strong>payout ratio</strong> — the share of
      earnings paid out — and <strong>free cash flow</strong>, the money actually available after the company
      has paid for its own upkeep. A company paying 90% of earnings as dividend has no room to absorb a bad
      year without cutting. A company paying 30% of strong free cash flow could double the dividend and still
      be comfortable.
    </p>
    <p class="guide-p">
      A twenty-five-year streak funded by borrowing is not a record of strength. It is a record of a balance
      sheet being spent.
    </p>

    <h2 class="guide-h2">The cyclical trap</h2>
    <p class="guide-p">
      Long dividend records cluster in sectors with steady, contract-like cash flows: utilities, mining,
      fertilisers, consumer staples. They are rarer in sectors that swing hard. That is not an accident — it is
      arithmetic. A commodity producer with a long record has usually survived by paying small, sustainable
      dividends rather than large, impressive ones.
    </p>
    <p class="guide-p">
      Which means the headline number can mislead about the income. A 2% yield on a share that has compounded
      is a different proposition from a 6% yield on a share whose price has gone nowhere for a decade while the
      payout stayed flat. Run the total return, not the yield.
    </p>

    <h2 class="guide-h2">The traps specific to Indian dividend investing</h2>
    <p class="guide-p">
      <strong>Dividends are taxed at your slab.</strong> Since 2020 the dividend is taxed in your hands, with
      TDS above the threshold. A 4% dividend in the 30% slab is 2.7% after tax. Compare that with what the same
      money would earn in a tax-free small-savings scheme before you call it income.
    </p>
    <p class="guide-p">
      <strong>The share price moves independently.</strong> A 4% dividend on a stock that fell 20% is not
      income; it is a smaller loss. This is the single most common error in dividend investing.
    </p>
    <p class="guide-p">
      <strong>A streak is history, not a covenant.</strong> Companies are under no obligation to keep paying.
      Several long records on the Indian market have been broken in bad years, and each time the share price
      fell further than the dividend was worth.
    </p>

    <h2 class="guide-h2">How to use a streak properly</h2>
    <p class="guide-p">
      Treat it as a filter, not a signal. Start with companies that have paid for a long time, then read three
      things yourself: the payout ratio against earnings, free cash flow against the dividend, and the debt on
      the balance sheet. If all three hold, the record is meaningful. If any one fails, the record is a
      coincidence that has not yet ended.
    </p>
    <p class="guide-p">
      The <a href="categories/dividend-champions.html">Dividend Champions records</a> on this site list the
      last ten payments for each company, with the date of each. Use the dates to see whether the dividend has
      been rising, flat or slipping — the pattern matters more than the count.
    </p>
    """,
)

SCSS = _shell(
    "Senior Citizens' Savings Scheme: when it beats a fixed deposit",
    "The highest rate available to most retirees is not automatically the best place for the money. Here is where it wins and where it ties your hands.",
    "Reviewed 15 November 2026",
    """
    <p class="guide-p">
      SCSS pays 8.20%, notified for the quarter beginning 1 October 2026. A senior-citizen fixed deposit at a
      large bank typically pays 0.25% to 0.50% above its normal rate. On paper SCSS usually wins. After tax and
      after the practical restrictions, the answer depends on how much you need the money to stay put.
    </p>

    <h2 class="guide-h2">The arithmetic</h2>
    <p class="guide-p">
      SCSS pays interest quarterly and returns the capital at maturity after five years. The interest is
      taxable at your slab, and TDS applies above the threshold. At the 20% slab with cess, an 8.20% SCSS
      deposit keeps about <strong>6.72%</strong>. A senior FD at 7.75% keeps about <strong>5.33%</strong>.
    </p>
    <p class="guide-p">
      On ₹20 lakh, that difference is roughly ₹28,000 a year — worth knowing, and worth checking against what
      your bank actually offers before you decide.
    </p>

    <h2 class="guide-h2">What SCSS gives you that a deposit does not</h2>
    <ul class="check-list">
      <li><span><strong>A government guarantee</strong>, not a bank one. Above ₹5 lakh, a bank deposit depends on the bank; SCSS depends on the sovereign.</span></li>
      <li><span><strong>A rate fixed for five years</strong>, notified when you invest. If rates fall, yours does not.</span></li>
      <li><span><strong>80C eligibility</strong> on the deposit, in the old regime.</span></li>
      <li><span><strong>Extension</strong> by three years at maturity, with the rate then in force.</span></li>
    </ul>

    <h2 class="guide-h2">What it takes away</h2>
    <p class="guide-p">
      <strong>The money is locked.</strong> Premature closure is allowed after one year, with a penalty on the
      rate already paid. Close it in the first year and you may get back less than you put in after adjustment.
    </p>
    <p class="guide-p">
      <strong>Interest is paid out, not compounded.</strong> That is deliberate — this is an income product —
      but it means the ₹20 lakh does not grow. If you do not need the quarterly income, you will need to
      reinvest it yourself, and the rate on that reinvestment is unknown today.
    </p>
    <p class="guide-p">
      <strong>There is a ceiling.</strong> ₹30 lakh per depositor, including extensions. Above that, SCSS
      cannot hold your whole corpus.
    </p>

    <h2 class="guide-h2">The comparison nobody runs</h2>
    <p class="guide-p">
      Against PPF, SCSS pays more and is available only to those over 60. Against a bank FD, SCSS pays more
      and is safer above ₹5 lakh. Against a debt mutual fund, SCSS has no interest-rate risk on the capital and
      no expense ratio — but also no liquidity.
    </p>
    <p class="guide-p">
      The honest way to compare is on the money you actually need. Split the corpus: five years of expenses
      that must never move, and the rest that can. SCSS is well suited to the part that must never move. It is
      a poor fit for money you may need for a medical bill or a family obligation next year.
    </p>

    <h2 class="guide-h2">Small practical points that catch people out</h2>
    <p class="guide-p">
      Open it at a post office or an authorised bank — the rate is the same. Bring proof of age, because the
      60-year threshold is checked. If you are between 55 and 60 and retired on superannuation or under a VRS,
      you can open one within a month of receiving your retirement benefits, subject to conditions; that window
      is narrow and worth diarising.
    </p>
    <p class="guide-p">
      The quarterly interest lands in your savings account. If TDS is deducted, file for a refund when you
      submit your return — many retirees overpay tax simply by not claiming it.
    </p>
    <p class="guide-p">
      Current rate and the quarter it applied: see the <a href="plans/senior-citizens-savings-scheme.html">SCSS
      page</a>, and run your own numbers in the <a href="calculators/savings.html">savings calculator</a>.
    </p>
    """,
)

PARENTS = _shell(
    "Health insurance for parents after 60: what changes",
    "Premium is the visible cost. Co-payment, waiting periods and room-rent caps are the ones that decide whether the cover works.",
    "Reviewed 15 November 2026",
    """
    <p class="guide-p">
      Buying health cover for a parent over 60 is a different exercise from buying it for yourself at 30. The
      premium is higher, the conditions are more likely to be pre-existing, and the policy design shifts in
      ways that are easy to miss until you claim.
    </p>

    <h2 class="guide-h2">1. Co-payment is standard, and it compounds</h2>
    <p class="guide-p">
      Most senior-citizen policies apply a co-payment — typically 10% to 20% of every claim. A 20% co-payment on
      a ₹4 lakh hospital bill leaves ₹80,000 with you. That is not a small print issue; it is the difference
      between cover and partial cover.
    </p>
    <p class="guide-p">
      Some policies waive the co-payment for a higher premium. Run the arithmetic: if the waiver costs ₹12,000
      a year and you claim once every three years, the waiver pays for itself on a single ₹2 lakh
      hospitalisation.
    </p>

    <h2 class="guide-h2">2. Pre-existing conditions and the waiting clock</h2>
    <p class="guide-p">
      Diabetes, hypertension and cardiac history are near-universal after 60. Most policies impose a waiting
      period of two to four years on them. During that window, related treatment is excluded — and "related" can
      be interpreted broadly.
    </p>
    <p class="guide-p">
      Declare everything. Non-disclosure is the most common reason claims are rejected years later, and insurers
      can and do check hospital records from before the policy started.
    </p>

    <h2 class="guide-h2">3. Room rent caps punish more than the room</h2>
    <p class="guide-p">
      A 1% cap on a ₹5 lakh sum insured is ₹5,000 a day. Most policies apply a <em>proportionate deduction</em>
      to the whole bill when you exceed it, not just the room charge. In a metro hospital, that single clause can
      cut a claim by a third.
    </p>

    <h2 class="guide-h2">4. Renewal is not guaranteed forever</h2>
    <p class="guide-p">
      Regulators have pushed insurers away from lifetime renewability being discretionary, but the mechanics
      still matter: if you let a policy lapse, re-entry at 68 after a cardiac event is effectively impossible
      or extremely expensive. Set the renewal on autopay and treat it as non-negotiable.
    </p>

    <h2 class="guide-h2">5. The sum insured is a decision about your savings</h2>
    <p class="guide-p">
      A ₹5 lakh cover in a metro is thin. One cardiac procedure with a week in ICU can cross it. For parents,
      ₹10 lakh is closer to adequate, and a policy with restoration is worth more than a slightly larger
      headline sum without it.
    </p>

    <h2 class="guide-h2">What to do before you buy</h2>
    <ul class="check-list">
      <li><span>Ask for the <strong>policy wording</strong>, not the brochure, and search it for four words: waiting, room, co-pay, sub-limit.</span></li>
      <li><span>Check whether your parents' usual hospital is in the <strong>cashless network</strong> — a network list from the insurer, not the agent.</span></li>
      <li><span>Compare the <strong>co-payment and waiting periods</strong> between two policies before comparing premiums. The cheaper premium is usually buying a worse claim.</span></li>
      <li><span>Declare every condition, in writing, and keep the acknowledgement.</span></li>
    </ul>
    <p class="guide-p">
      The <a href="categories/health-insurance.html">health insurance records</a> on this site summarise what
      each insurer says about its own plans, with the date checked. They are a starting point for reading the
      wording, not a substitute for it.
    </p>
    """,
)

RATES = _shell(
    "Why the government's small-savings rates change every quarter",
    "PPF at 7.10% is not a number someone chose. It is the output of a formula — and knowing how it moves tells you when to expect the next change.",
    "Reviewed 15 November 2026",
    """
    <p class="guide-p">
      Every quarter the Finance Ministry notifies the interest rates on small-savings schemes: PPF, Sukanya
      Samriddhi, National Savings Certificate, Kisan Vikas Patra, Senior Citizens' Savings Scheme, the Post
      Office Monthly Income Scheme and time deposits. Those rates decide what millions of households earn, and
      most people have no idea why they move.
    </p>

    <h2 class="guide-h2">The formula, in outline</h2>
    <p class="guide-p">
      Since 2016 the rates are intended to track government bond yields, with fixed spreads over the benchmark
      for each scheme. The idea is that a small-savings rate should not drift far from what the government
      itself pays to borrow. When the ten-year bond yield falls, the formula points to a lower PPF rate. When it
      rises, the opposite.
    </p>
    <p class="guide-p">
      In practice the government retains discretion, and has often held rates steady for several quarters at a
      time rather than following every small move in yields. So the formula is a guide to direction, not a
      promise of the exact number.
    </p>

    <h2 class="guide-h2">Why the rates were cut through the 2016–2020 period</h2>
    <p class="guide-p">
      Because bond yields fell. The ten-year yield declined steadily through that period, and the notified rates
      followed with a lag — PPF moved from 8.7% to 7.1% across a handful of revisions. Nobody decided savers
      should earn less; the reference rate moved.
    </p>

    <h2 class="guide-h2">Why the quarter matters when you invest</h2>
    <p class="guide-p">
      The rate you get is the one in force when you make the deposit, not the one in force at maturity.
    </p>
    <ul class="check-list">
      <li><span><strong>PPF and Sukanya Samriddhi</strong> apply the current rate to the balance each year. A cut affects everything you have saved so far.</span></li>
      <li><span><strong>NSC and KVP</strong> fix the rate when you buy. A certificate bought before a cut keeps its old rate for its full term — one of the few genuine advantages of these products.</span></li>
      <li><span><strong>SCSS and Post Office MIS</strong> fix the rate for the term at the time you open the account.</span></li>
    </ul>
    <p class="guide-p">
      That difference is the practical reason the "when" of an investment matters as much as the "what" for
      these schemes.
    </p>

    <h2 class="guide-h2">What this means for a decision today</h2>
    <p class="guide-p">
      If you believe yields are heading lower, fixing a rate through NSC or SCSS protects you; PPF will follow
      the cuts down. If yields are heading higher, the reverse is true — a floating rate is an advantage.
    </p>
    <p class="guide-p">
      Either way, the number you should act on is the one with a date next to it. That is why every rate on this
      site prints the quarter it applied, and links to the notification. A rate without a date is a
      guess about which quarter you are in.
    </p>

    <h2 class="guide-h2">Where to watch</h2>
    <p class="guide-p">
      Rates are notified at the end of each quarter for the next one — the dates to remember are 1 January,
      1 April, 1 July and 1 October. The <a href="rates.html">rates page</a> carries the current figure for each
      scheme with its notification date, and every plan page repeats the date beside the rate it uses.
    </p>
    """,
)

EMERGENCY = _shell(
    "The emergency fund: how much, and where to keep it in India",
    "Before returns, before taxes, before any product comparison — the money that stops a bad month becoming a bad year.",
    "Reviewed 15 November 2026",
    """
    <p class="guide-p">
      Every product comparison on this site assumes you have money you will not need for years. That assumption
      fails for most people, and it fails at the worst possible moment. The emergency fund is the piece of
      financial planning that makes every other piece possible.
    </p>

    <h2 class="guide-h2">How much</h2>
    <p class="guide-p">
      Three to six months of essential expenses. Not income — expenses. Rent or EMI, utilities, school fees,
      groceries, transport, insurance premiums, and the minimum on any debt. If your household spends ₹60,000 a
      month on essentials, the target is ₹1.8 lakh to ₹3.6 lakh.
    </p>
    <p class="guide-p">
      Lean towards six months if your income is variable, if you are the only earner, if your job is in a
      cyclical industry, or if someone in the family has a condition that might need treatment. Lean towards
      three if you have two stable incomes and no dependants.
    </p>

    <h2 class="guide-h2">Where to keep it — three rules</h2>
    <p class="guide-p">
      <strong>1. It must be available in 24 hours.</strong> Not five years, not at maturity, not subject to a
      penalty that makes you think twice.
    </p>
    <p class="guide-p">
      <strong>2. It must not fall in value.</strong> This money is not invested. A fund that can be down 15% in
      a bad month is the wrong home for the money you need after losing a job.
    </p>
    <p class="guide-p">
      <strong>3. It must be separate from your spending account.</strong> If it sits in the account you use for
      groceries, it will quietly disappear on a good month and be missing on a bad one.
    </p>

    <h2 class="guide-h2">The realistic options</h2>
    <ul class="check-list">
      <li><span><strong>A separate savings account</strong> at a different bank, with autopay switched off. Lowest effort, lowest return — and that is fine, because this is insurance, not investment.</span></li>
      <li><span><strong>A sweep-in FD linked to savings.</strong> Slightly better rate, still instant. Watch the minimum balance rules and the tax on the interest.</span></li>
      <li><span><strong>A liquid or overnight mutual fund.</strong> Better return, one-day redemption. Acceptable if you understand that the NAV can dip slightly and that redemption is not instantaneous.</span></li>
      <li><span><strong>Not a fixed deposit with a penalty</strong>, not PPF, not an endowment policy, not equity. All four fail one of the three rules above.</span></li>
    </ul>

    <h2 class="guide-h2">The tax point nobody mentions</h2>
    <p class="guide-p">
      Interest on your emergency fund is taxed at your slab. At 30%, a 3% savings account yields about 2.1%
      after tax — below inflation, which is the correct trade. You are paying a small amount to avoid a large
      loss, exactly as you do with insurance.
    </p>

    <h2 class="guide-h2">Building it when you have nothing set aside</h2>
    <p class="guide-p">
      Start with one month of expenses. Automate a transfer on salary day, before the spending starts. Once you
      reach one month, aim for three, then six. It is slower than it sounds and faster than it feels.
    </p>
    <p class="guide-p">
      Do this before you open a PPF account, before you start a SIP, and before you compare fixed deposit rates
      — because without it, the first emergency forces you to break whichever of those you chose, usually at the
      worst possible time.
    </p>
    """,
)

