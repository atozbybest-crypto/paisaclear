TAX3 = """
    <h2 class="guide-h2">NSC and KVP: the mechanics people mix up</h2>
    <p class="guide-p">
      NSC accumulates interest and pays it with the principal at five years. KVP pays nothing until maturity, when
      the amount has doubled — currently over roughly 115 months. Neither pays you anything along the way, which
      is why both suit money you will not touch rather than income you need.
    </p>
    <p class="guide-p">
      The tax treatment differs in a way that matters: NSC qualifies for 80C and its interest is taxable as it
      accrues; KVP has no 80C benefit and its built-in interest is taxable at maturity. For a 30% slab saver, KVP's
      apparent doubling is much less impressive after tax than the brochure suggests.
    </p>

    <h2 class="guide-h2">Using the ₹1.5 lakh 80C limit well</h2>
    <p class="guide-p">
      The limit is shared across PPF, NSC, life insurance premiums, EPF, principal on a home loan and tuition
      fees. If your EPF already consumes most of it, adding PPF buys no extra deduction — only the tax-free
      return. That is still worth having, but it is a different reason than the one most people give.
    </p>
    <p class="guide-p">
      Check your EPF contribution for the year first. Many salaried savers discover that 12% of basic plus
      dearness already fills a large part of the ₹1.5 lakh, and that the PPF deposit is being made for the return
      rather than the deduction.
    </p>
"""

DIVIDEND3 = """
    <h2 class="guide-h2">Dividend or buyback: where the cash comes from</h2>
    <p class="guide-p">
      A dividend pays cash to every shareholder and is taxed at the shareholder's slab. A buyback returns cash by
      purchasing shares, and is taxed differently — historically more favourably for the company, and now subject
      to its own rules. For an investor, the practical difference is the tax treatment and whether you choose to
      participate.
    </p>
    <p class="guide-p">
      A company shifting from dividends to buybacks is not necessarily being generous; it may be choosing the
      more tax-efficient route for its shareholders. Read the announcement, not just the headline payout.
    </p>

    <h2 class="guide-h2">Building an income plan from dividend stocks</h2>
    <p class="guide-p">
      If the goal is annual income rather than total return, three rules help. Diversify across at least eight to
      ten payers in different sectors, so one cut does not halve your income. Prefer a lower yield with a
      comfortable payout ratio over a high yield with a stretched one. And keep two years of expected dividend
      income in cash, because dividends are declared, not guaranteed, and a bad year for the sector is a bad year
      for the income.
    </p>
    <p class="guide-p">
      Then measure it honestly: after tax, after the years when a payer cut, and against what the same capital
      would have earned in a tax-free small-savings scheme. Most dividend portfolios look better before that
      comparison than after it.
    </p>
"""

SCSS3 = """
    <h2 class="guide-h2">Joint accounts and nomination</h2>
    <p class="guide-p">
      SCSS allows a joint account with a spouse, and the deposit is treated as belonging to the first holder for
      the ₹30 lakh cap. A nominee is mandatory in practice — without one, the balance goes through succession,
      which is slow and avoidable. Add the nominee at opening; changing it later requires a form and a visit.
    </p>
    <p class="guide-p">
      If both spouses are over 60, two separate single accounts are usually cleaner than one joint account:
      each gets its own ₹30 lakh cap and its own quarterly payout.
    </p>

    <h2 class="guide-h2">The transition at 60</h2>
    <p class="guide-p">
      The year you turn 60, four things become available at once: SCSS, higher FD rates for seniors, a higher
      basic exemption limit, and in some cases a higher 80D deduction for health insurance. The efficient
      sequence is usually to move maturing FDs into SCSS up to the cap, keep a liquid cushion outside it, and
      review health cover before the next birthday makes it dearer.
    </p>
    <p class="guide-p">
      The mistake is moving everything into SCSS in one go and then discovering that a medical bill or a family
      obligation needs money that is now locked for five years.
    </p>
"""

PARENTS3 = """
    <h2 class="guide-h2">Senior-citizen policies versus ordinary ones</h2>
    <p class="guide-p">
      A dedicated senior-citizen policy usually has a higher entry age, no upper age limit for renewal, shorter
      pre-existing waiting periods, and a co-payment. An ordinary policy taken earlier may have better terms but
      stops accepting new entrants at a certain age.
    </p>
    <p class="guide-p">
      The practical rule: if a parent already has a policy, keep renewing it even if a newer one looks cheaper.
      Continuity of waiting periods is worth more than a small premium difference.
    </p>

    <h2 class="guide-h2">If the insurer declines</h2>
    <p class="guide-p">
      A decline is not the end. Options include a policy with a longer waiting period, a higher co-payment, a
      lower sum insured, or a dedicated condition-specific product. A common fallback is a fixed-benefit plan
      that pays a lump sum on specified diagnoses rather than reimbursing bills — less useful but obtainable when
      indemnity cover is not.
    </p>
    <p class="guide-p">
      Whatever the route, get the reason for the decline in writing. It determines what to disclose to the next
      insurer, and non-disclosure of a previous decline is itself a ground for rejection later.
    </p>
"""

